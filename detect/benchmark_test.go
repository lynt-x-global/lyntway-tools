func digits(r *rand.Rand, n int) string {
	var sb strings.Builder
	for i := 0; i < n; i++ {
		sb.WriteByte(byte('0' + r.Intn(10)))
	}
	return sb.String()
}

func upper(r *rand.Rand, n int, alphabet string) string {
	var sb strings.Builder
	for i := 0; i < n; i++ {
		sb.WriteByte(alphabet[r.Intn(len(alphabet))])
	}
	return sb.String()
}

func luhnCheck(body string) byte {
	sum := 0
	double := true
	for i := len(body) - 1; i >= 0; i-- {
		d := int(body[i] - '0')
		if double {
			d *= 2
			if d > 9 {
				d -= 9
			}
		}
		sum += d
		double = !double
	}
	return byte('0' + (10-sum%10)%10)
}

func card(r *rand.Rand, valid bool) (string, []int) {
	type brand struct {
		prefix string
		length int
		groups []int
	}
	brands := []brand{
		{"4", 16, []int{4, 4, 4, 4}}, {"51", 16, []int{4, 4, 4, 4}}, {"55", 16, []int{4, 4, 4, 4}},
		{"37", 15, []int{4, 6, 5}}, {"6011", 16, []int{4, 4, 4, 4}}, {"2221", 16, []int{4, 4, 4, 4}},
	}
	b := brands[r.Intn(len(brands))]
	body := b.prefix + digits(r, b.length-len(b.prefix)-1)
	check := luhnCheck(body)
	if !valid {
		check = byte('0' + (int(check-'0')+1+r.Intn(8))%10)
	}
	return body + string(check), b.groups
}

func formatGroups(s string, groups []int, sep string) string {
	var parts []string
	i := 0
	for _, g := range groups {
		parts = append(parts, s[i:i+g])
		i += g
	}
	return strings.Join(parts, sep)
}

func ibanCheck(country, bban string) string {
	rearranged := bban + country + "00"
	var numeric strings.Builder
	for _, c := range rearranged {
		if c >= 'A' && c <= 'Z' {
			numeric.WriteString(fmt.Sprint(int(c-'A') + 10))
		} else {
			numeric.WriteRune(c)
		}
	}
	mod := 0
	for _, c := range numeric.String() {
		mod = (mod*10 + int(c-'0')) % 97
	}
	return fmt.Sprintf("%02d", 98-mod)
}

func iban(r *rand.Rand, valid bool) string {
	var country, bban string
	switch r.Intn(3) {
	case 0:
		country, bban = "GB", upper(r, 4, "ABCDEFGHIJKLMNOPQRSTUVWXYZ")+digits(r, 14)
	case 1:
		country, bban = "DE", digits(r, 18)
	default:
		country, bban = "NL", upper(r, 4, "ABCDEFGHIJKLMNOPQRSTUVWXYZ")+digits(r, 10)
	}
	check := ibanCheck(country, bban)
	if !valid {
		n := (int(check[0]-'0')*10 + int(check[1]-'0') + 1 + r.Intn(90)) % 97
		if n < 2 {
			n += 2
		}
		check = fmt.Sprintf("%02d", n)
	}
	full := country + check + bban
	if r.Intn(2) == 0 {
		return full
	}
	var groups []string
	for i := 0; i < len(full); i += 4 {
		end := i + 4
		if end > len(full) {
			end = len(full)
		}
		groups = append(groups, full[i:end])
	}
	return strings.Join(groups, " ")
}

func ssn(r *rand.Rand, valid bool) string {
	area := 1 + r.Intn(665)
	if !valid {
		area = []int{0, 666, 900 + r.Intn(100)}[r.Intn(3)]
	}
	return fmt.Sprintf("%03d-%02d-%04d", area, 1+r.Intn(99), 1+r.Intn(9999))
}

var verhoeffInv = [10]int{0, 4, 3, 2, 1, 5, 6, 7, 8, 9}

func verhoeffDigit(body string) byte {
	c := 0
	for i := 0; i < len(body); i++ {
		d := int(body[len(body)-1-i] - '0')
		c = verhoeffD[c][verhoeffP[(i+1)%8][d]]
	}
	return byte('0' + verhoeffInv[c])
}

func aadhaar(r *rand.Rand, valid bool) string {
	body := fmt.Sprint(2+r.Intn(8)) + digits(r, 10)
	check := verhoeffDigit(body)
	if !valid {
		check = byte('0' + (int(check-'0')+1+r.Intn(8))%10)
	}
	full := body + string(check)
	if r.Intn(2) == 0 {
		return full
	}
	return full[0:4] + " " + full[4:8] + " " + full[8:12]
}

func nino(r *rand.Rand) string {
	const first = "ABCEGHJKLMNOPRSTWXYZ"
	const second = "ABCEGHJKLMNPRSTWXYZ"
	var prefix string
	for {
		prefix = upper(r, 1, first) + upper(r, 1, second)
		switch prefix {
		case "BG", "GB", "NK", "KN", "TN", "NT", "ZZ":
			continue
		}
		break
	}
	d := digits(r, 6)
	suffix := upper(r, 1, "ABCD")
	if r.Intn(2) == 0 {
		return prefix + d + suffix
	}
	return prefix + " " + d[0:2] + " " + d[2:4] + " " + d[4:6] + " " + suffix
}

