// buildCorpus returns the same documents on every call.
func buildCorpus() []document {
	r := rand.New(rand.NewSource(20260917))
	var docs []document
	add := func(fill func(b *builder)) {
		b := &builder{}
		fill(b)
		docs = append(docs, b.doc())
	}
	for i := 0; i < 150; i++ {
		add(func(b *builder) {
			c, g := card(r, true)
			seps := []string{"", " ", "-"}
			sep := seps[r.Intn(3)]
			v := c
			if sep != "" {
				v = formatGroups(c, g, sep)
			}
			b.text("Please charge ")
			b.entity(ClassCreditCard, v)
			b.text(" for the renewal.")
		})
		add(func(b *builder) { b.text("Pay to IBAN "); b.entity(ClassIBAN, iban(r, true)); b.text(" by Friday.") })
		add(func(b *builder) { b.text("SSN on the form: "); b.entity(ClassUSSSN, ssn(r, true)); b.text(".") })
		add(func(b *builder) { b.text("Aadhaar "); b.entity(ClassINAadhaar, aadhaar(r, true)); b.text(" verified.") })
		add(func(b *builder) { b.text("NI number "); b.entity(ClassUKNINO, nino(r)); b.text(" on the payslip.") })
		add(func(b *builder) { b.text("PAN "); b.entity(ClassINPAN, pan(r)); b.text(" is linked.") })
		add(func(b *builder) {
			b.text("Reach ")
			b.entity(ClassEmail, email(r))
			b.text(" or call ")
			b.entity(ClassPhone, phone(r))
			b.text(" today.")
		})
		add(func(b *builder) { b.text("Login from "); b.entity(ClassIPv4, ipv4(r)); b.text(" was blocked.") })
	}
	for i := 0; i < 180; i++ {
		add(func(b *builder) {
			c, v := secret(r)
			b.text("config: ")
			b.entity(c, v)
			b.text("\n")
		})
	}
	for i := 0; i < 3; i++ {
		for _, inj := range injections {
			inj := inj
			add(func(b *builder) {
				b.text("Retrieved page says: ")
				b.entity(inj.class, inj.text)
			})
		}
	}
	for i := 0; i < 40; i++ {
		for _, neg := range hardNegatives {
			neg := neg
			add(func(b *builder) { b.text(neg(r)) })
		}
	}
	return docs
}

type score struct{ tp, fp, fn int }

func (s score) precision() float64 {
	if s.tp+s.fp == 0 {
		return 1
	}
	return float64(s.tp) / float64(s.tp+s.fp)
}

func (s score) recall() float64 {
	if s.tp+s.fn == 0 {
		return 1
	}
	return float64(s.tp) / float64(s.tp+s.fn)
}

// scoreCorpus matches findings to labels of the same class that overlap.
// For the injection classes the label is the whole sentence and the rule
// matches a phrase inside it, so overlap, not equality, is the test.
func scoreCorpus(rs *Ruleset, docs []document) map[Class]*score {
	scores := map[Class]*score{}
	get := func(c Class) *score {
		if scores[c] == nil {
			scores[c] = &score{}
		}
		return scores[c]
	}
	for _, d := range docs {
		found := rs.Scan([]byte(d.text))
		matched := make([]bool, len(d.spans))
		for _, f := range found {
			hit, again := false, false
			for i, e := range d.spans {
				if e.class != f.Class || f.Start >= e.end || e.start >= f.End {
					continue
				}
				if matched[i] {
					// A second finding inside a label already counted —
					// both chat markers in one injected sentence — is the
					// same detection, not a false alarm.
					again = true
					continue
				}
				matched[i], hit = true, true
				break
			}
			switch {
			case hit:
				get(f.Class).tp++
			case !again:
				get(f.Class).fp++
			}
		}
		for i, e := range d.spans {
			if !matched[i] {
				get(e.class).fn++
			}
		}
	}
	return scores
}

