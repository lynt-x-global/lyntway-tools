func TestDetectionBenchmark(t *testing.T) {
	docs := buildCorpus()
	scores := scoreCorpus(Default(), docs)

	var classes []string
	for c := range scores {
		classes = append(classes, string(c))
	}
	sort.Strings(classes)

	var report strings.Builder
	fmt.Fprintf(&report, "| Class | Labelled | Found correctly | Missed | False alarms | Precision | Recall |\n")
	fmt.Fprintf(&report, "|---|---:|---:|---:|---:|---:|---:|\n")
	for _, name := range classes {
		c := Class(name)
		s := scores[c]
		fmt.Fprintf(&report, "| `%s` | %d | %d | %d | %d | %.3f | %.3f |\n",
			c, s.tp+s.fn, s.tp, s.fn, s.fp, s.precision(), s.recall())
		floor, ok := benchmarkFloors[c]
		if !ok {
			t.Errorf("%s has no floor; add one", c)
			continue
		}
		if s.precision() < floor.precision || s.recall() < floor.recall {
			t.Errorf("%s: precision %.3f (floor %.2f), recall %.3f (floor %.2f)",
				c, s.precision(), floor.precision, s.recall(), floor.recall)
		}
	}
	t.Logf("%d documents\n%s", len(docs), report.String())

	if os.Getenv("LYNTWAY_WRITE_BENCHMARK") == "1" {
		doc := fmt.Sprintf(benchmarkDocHeader, len(docs), Default().Version()) + report.String() + benchmarkDocFooter
		if err := os.WriteFile("../docs/detection-benchmark.md", []byte(doc), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

