// A measured answer to "how good is detection?".
//
// Nobody could say. There was no precision or recall figure, no labelled
// corpus, and so no way to notice a rule getting worse. This builds a
// labelled synthetic corpus deterministically — the same documents on every
// run — scores the deterministic ruleset against it, prints the result, and
// fails if any class falls below the floor recorded when it was last
// measured. LYNTWAY_WRITE_BENCHMARK=1 rewrites docs/detection-benchmark.md.
//
// What it is not:
//
//   - Real traffic. Every document here was generated by this file. The
//     figures say how the rules behave on the shapes written below, which
//     include the hard cases we know about; they say nothing about shapes
//     nobody here thought of.
//   - The model tier. Names, addresses and free-text personal data are
//     found by the analyzer, which is not in this module and not measured.
//   - Languages other than English, for the injection classes.
//
// Positives are generated to be valid (checksums pass, prefixes are
// allocated). Negatives are the confusable things that appear next to them
// in real text: order numbers, card-shaped numbers that fail Luhn, IBANs
// with a wrong check, timestamps, UUIDs, versions, git hashes, prices, and
// prose about the topics the injection rules watch for.

type expected struct {
	class      Class
	start, end int
}

type document struct {
	text  string
	spans []expected
}

type builder struct {
	sb    strings.Builder
	spans []expected
}

func (b *builder) text(s string) { b.sb.WriteString(s) }

func (b *builder) entity(c Class, s string) {
	start := b.sb.Len()
	b.sb.WriteString(s)
	b.spans = append(b.spans, expected{class: c, start: start, end: b.sb.Len()})
}

// entityBoth labels one span with two classes.
//
// Some sentences genuinely are two things at once — an announcement that the
// bank details changed *and* an instruction not to use the old account. With
// only one label the second, correct finding scores as a false alarm, and the
// pressure that creates is to weaken a rule that is working.
func (b *builder) entityBoth(c1, c2 Class, s string) {
	start := b.sb.Len()
	b.sb.WriteString(s)
	end := b.sb.Len()
	b.spans = append(b.spans,
		expected{class: c1, start: start, end: end},
		expected{class: c2, start: start, end: end})
}

func (b *builder) doc() document { return document{text: b.sb.String(), spans: b.spans} }

